#!/usr/bin/env python3
"""newmap.py: write the loose data files for a new (custom) map / dungeon by cloning a shipped map.

    python3 tools/dungeon/newmap.py <spec.json|spec.toml> -o <outdir> [--refresh]

Nothing is invented: every element and attribute in the output comes from the reference map's own rows
(cloned text, original formatting/BOM/line endings kept); spec overrides may only set attributes that
some shipped row of the same table/tag already carries, and id-valued attributes are checked against the
shipped tables.  Two data sets are written, because the client and the local server read different XML:

  client-xml/   -> KMS client Xml.m2d     table/fielddata.xml (fieldData row), table/dungeonroom.xml,
                                          string/<lang>/mapname.xml, mapxblock/<xb>.xml, trigger/<xb>/
  server-xml/   -> server Xml.m2d (v1.3.2) map/<id>.xml, table/na/dungeonroom.xml, string/en/mapname.xml,
                                          mapxblock/<xb>.xml, trigger/<xb>/
  server/       -> Server.m2d             table/Server/InstanceField.xml (only if the reference has a row)
  exported/     -> Exported.m2d           xblock/<xb>.xblock      (copy of the reference, or spec xblock_file)
  terrain/      -> PrecomputedTerrain.m2d <xb>.tok                (copy of the reference, or spec tok_file)
  image/        -> Image.m2d              map/minimap/<id>.dds    (generated by minimap.py, or minimap_file,
                                                                   or the reference's with "minimap": "reference")
  awm/          -> asset-web-metadata.m2d <tag>.nt                (whole .nt files plus the new xblock's triples,
                                                                   cloned from the reference xblock's own triples;
                                                                   the client resolves urn:emergent-world:<XB> here)
  manifest.json -> what pack.py repacks into which archive

Spec keys (see tools/dungeon/example-spec.json and README.md):
  map_id, xblock, clone_from                      required
  names {lang: text}                              map name; langs not given fall back to "en", then any
  map {tag: {attr: value}}                        overrides on the environment children (property, drop, bgm, fov,
                                                  hdr, camera, shadow, ui, indoor, cashCall, ...), both sides
  client_map / server_map                         same, one side only
  mapxblock {tag: {attr: value}}                  e.g. {"clientProperty": {"bgDay": "BG_Indoor_A.dds"}}
  instance_field  "clone" (default) | false | {attr: value}   server InstanceField row (instanceID = next after the max of its instanceType)
  dungeon_room {id, clone_from, set{}, client_set{}, server_set{}}   fieldIDs is set to the new map id
  copy_triggers (default true), trigger_dir, xblock_file, tok_file, minimap_file
  minimap  "generate" (default without minimap_file) | "reference" | false
           generate: tools/dungeon/minimap.py renders the xblock (xblock_file or the reference's) into the
           DDS, writes a <minimap> camera node into both mapxblock xmls and drops minimapInvisible from
           the fieldData row and server map (unless the spec sets it); on failure it falls back to
           "reference" with a note.  reference: copy the reference map's DDS (old behaviour).  false: none.
  minimap_project                                 Toolbench project dir for tokgeom --project (loose NIFs)
  sources {client_xml, server_xml, server_m2d, resource}   archive paths (defaults from MS2_CLIENT_DATA / MS2_SERVER_DATA,
                                                  see tools/modtools_config.py)
Relative trigger_dir, xblock_file, tok_file, minimap_file and minimap_project paths are looked up next to the
spec file first, then in the current directory, then in the repo root.
"""
import argparse, json, os, re, shutil, subprocess, sys, uuid
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "tools"))
import modtools_config as cfg  # noqa: E402
from modtools_config import M2D_DLL, dotnet_env  # noqa: E402,F401  (other tools import them from here)

# spec "sources" key -> (setting, path under it)
DEFAULT_SOURCES = {
    "client_xml": ("MS2_CLIENT_DATA", "Xml.m2d"),
    "server_xml": ("MS2_SERVER_DATA", "Xml.m2d"),
    "server_m2d": ("MS2_SERVER_DATA", "Server.m2d"),
    "resource": ("MS2_CLIENT_DATA", "Resource"),
}


def resolve_sources(spec):
    """The archive paths: spec "sources" first, then the settings.  Stops, naming the setting, if one is missing."""
    src = {}
    given = spec.get("sources", {})
    for key, (setting, rel) in DEFAULT_SOURCES.items():
        if key in given:
            p = Path(given[key])
            src[key] = p if p.is_absolute() else REPO / p
        else:
            v = cfg.get(setting)
            if not v:
                raise SystemExit(cfg.missing_message(setting, f"the spec has no sources.{key}, so reading the archives"))
            src[key] = Path(v) / rel
    return src


class SpecError(Exception):
    pass


# ---------------------------------------------------------------- m2d access

def m2d(*args, capture=True):
    r = subprocess.run(["dotnet", str(cfg.ensure_m2d()), *map(str, args)], env=dotnet_env(),
                       capture_output=capture, text=True)
    if r.returncode != 0:
        raise SystemExit(f"m2d {' '.join(map(str, args))} failed:\n{r.stderr}")
    return r.stdout


class Archive:
    """Lazily extracted view of one .m2d (cached under <cache>/<key>/)."""

    def __init__(self, path, cache, key, refresh):
        self.path = Path(path)
        if not self.path.is_file():
            raise SystemExit(f"archive not found: {self.path}")
        self.dir = Path(cache) / key
        lst = Path(cache) / f"{key}.lst"
        stamp = f"{self.path.resolve()} {self.path.stat().st_size} {self.path.stat().st_mtime_ns}"
        stampf = Path(cache) / f"{key}.stamp"
        if refresh or not lst.is_file() or not stampf.is_file() or stampf.read_text() != stamp:
            shutil.rmtree(self.dir, ignore_errors=True)
            lst.parent.mkdir(parents=True, exist_ok=True)
            lst.write_text(m2d("list", self.path))
            stampf.write_text(stamp)
        self.names = lst.read_text().split()
        self.lower = {n.lower(): n for n in self.names}

    def has(self, name):
        return name.lower() in self.lower

    def under(self, prefix):
        p = prefix.lower()
        return [n for n in self.names if n.lower().startswith(p)]

    def fetch(self, *prefixes):
        """Extract entries starting with any prefix (once); returns nothing."""
        need = [p for p in prefixes if not (self.dir / f".got_{p.replace('/', '_')}").exists()]
        if need:
            m2d("extract", self.path, self.dir, *need)
            for p in need:
                (self.dir / f".got_{p.replace('/', '_')}").touch()

    def file(self, name):
        real = self.lower.get(name.lower())
        if real is None:
            return None
        f = self.dir / real
        if not f.exists():
            self.fetch(real)
        return f


# ---------------------------------------------------------------- text helpers (format-preserving)

class XText:
    def __init__(self, path):
        raw = Path(path).read_bytes()
        self.bom = raw.startswith(b"\xef\xbb\xbf")
        self.text = raw[3:].decode("utf-8") if self.bom else raw.decode("utf-8")
        self.nl = "\r\n" if "\r\n" in self.text else "\n"

    def write(self, path):
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        data = self.text.encode("utf-8")
        Path(path).write_bytes((b"\xef\xbb\xbf" if self.bom else b"") + data)

    def comment_spans(self):
        return [(m.start(), m.end()) for m in re.finditer(r"<!--.*?-->", self.text, re.S)]

    def find_live(self, pattern, flags=0):
        """All matches of pattern outside <!-- --> comments."""
        spans = self.comment_spans()
        return [m for m in re.finditer(pattern, self.text, flags)
                if not any(a <= m.start() < b for a, b in spans)]

    def insert_after(self, m, block):
        self.text = self.text[:m.end()] + block + self.text[m.end():]


def esc(v):
    return (str(v).replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;").replace(">", "&gt;"))


def set_attr(tag, attr, value):
    """Set attr on one start tag string (`<x a="1" />`); appends it if absent."""
    pat = re.compile(r'(\s' + re.escape(attr) + r'=")[^"]*(")')
    if pat.search(tag):
        return pat.sub(lambda m: m.group(1) + esc(value) + m.group(2), tag, count=1)
    return re.sub(r'\s*(/?>)$', lambda m: f' {attr}="{esc(value)}" ' + m.group(1)
                  if m.group(1) == "/>" else f' {attr}="{esc(value)}">', tag, count=1)


def get_attr(tag, attr):
    m = re.search(r'\s' + re.escape(attr) + r'="([^"]*)"', tag)
    return m.group(1) if m else None


def attr_universe(texts, tag):
    """attribute names carried by <tag ...> anywhere in the given texts."""
    names = set()
    for t in texts:
        for st in re.findall(r"<" + re.escape(tag) + r"\s[^>]*>", t):
            names.update(re.findall(r'\s(\w+)="', st))
    return names


def apply_tag_overrides(block, overrides, universes, where):
    """overrides {tag: {attr: value}} on the first <tag ...> in block. universes(tag) -> allowed attr set."""
    for tag, attrs in overrides.items():
        m = re.search(r"<" + re.escape(tag) + r"(\s[^>]*)?/?>", block)
        if not m:
            raise SpecError(f"{where}: the reference has no <{tag}> element (cannot add elements, only attributes)")
        allowed = universes(tag)
        st = m.group(0)
        for a, v in attrs.items():
            if a not in allowed:
                raise SpecError(f"{where}: <{tag} {a}=...> is not used by any shipped row; allowed: "
                                f"{', '.join(sorted(allowed))}")
            st = set_attr(st, a, v)
        block = block[:m.start()] + st + block[m.end():]
    return block


# ---------------------------------------------------------------- id sets for validation

def ids_of(text, tag, attr):
    out = set()
    for st in re.findall(r"<" + tag + r"\s[^>]*>", text):
        v = get_attr(st, attr)
        if v not in (None, ""):
            try:
                out.add(int(v))
            except ValueError:
                pass
    return out


def int_list(v):
    return [int(x) for x in re.split(r"[,\s]+", str(v).strip()) if x != ""]


# ---------------------------------------------------------------- main generator

class Gen:
    def __init__(self, spec, out, refresh):
        self.spec = spec
        self.out = Path(out)
        self.written = {}  # area -> [entry names]
        src = resolve_sources(spec)
        cache = self.out / "_ref"
        self.cx = Archive(src["client_xml"], cache, "client-xml", refresh)
        self.sx = Archive(src["server_xml"], cache, "server-xml", refresh)
        self.sv = Archive(src["server_m2d"], cache, "server", refresh)
        res = src["resource"]
        self.ex = Archive(res / "Exported.m2d", cache, "exported", refresh)
        self.pt = Archive(res / "PrecomputedTerrain.m2d", cache, "terrain", refresh)
        self.im = Archive(res / "Image.m2d", cache, "image", refresh)
        self.aw = Archive(res / "asset-web-metadata.m2d", cache, "awm", refresh)
        self.sources = {"client_xml": src["client_xml"], "server_xml": src["server_xml"],
                        "server_m2d": src["server_m2d"],
                        "exported": res / "Exported.m2d", "terrain": res / "PrecomputedTerrain.m2d",
                        "image": res / "Image.m2d", "awm": res / "asset-web-metadata.m2d"}
        self.errors = []

        try:
            self.mid = int(spec["map_id"])
            self.ref = int(spec["clone_from"])
            self.xb = str(spec["xblock"]).lower()
        except KeyError as e:
            raise SpecError(f"spec: missing required key {e}")
        if spec.get("layout") and not spec.get("xblock_file"):
            raise SpecError('spec: "layout" needs build.py, which generates the xblock (mkxblock.py) first')
        if not re.fullmatch(r"[0-9a-z_]+", self.xb):
            raise SpecError("spec: xblock name must be [0-9a-z_]+ (archive names are lower case)")

    def err(self, msg):
        self.errors.append(msg)

    def emit(self, area, name, xt_or_path):
        dst = self.out / area / name
        dst.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(xt_or_path, XText):
            xt_or_path.write(dst)
        else:
            shutil.copyfile(xt_or_path, dst)
        self.written.setdefault(area, []).append(name)

    # -- reference data
    def load(self):
        cx, sx, sv = self.cx, self.sx, self.sv
        self.fielddata = XText(cx.file("table/fielddata.xml"))
        self.c_maps = ids_of(self.fielddata.text, "fieldData", "id")
        sx.fetch("map/")
        self.s_maps = {int(Path(n).stem) for n in sx.under("map/") if re.fullmatch(r"map/\d+\.xml", n.lower())}
        self.s_maptexts = None  # loaded on demand (attr universe)
        if self.ref not in self.c_maps:
            self.err(f"clone_from {self.ref}: no fieldData row in the client table/fielddata.xml")
        if self.ref not in self.s_maps:
            self.err(f"clone_from {self.ref}: no map/{self.ref:08d}.xml in the server Xml.m2d")
        if self.mid in self.c_maps or self.mid in self.s_maps:
            self.err(f"map_id {self.mid} already exists in the shipped data")
        for a, name in ((cx, f"mapxblock/{self.xb}.xml"), (sx, f"mapxblock/{self.xb}.xml"),
                        (self.ex, f"xblock/{self.xb}.xblock"), (self.pt, f"{self.xb}.tok")):
            if a.has(name):
                self.err(f"xblock name {self.xb}: {name} already exists in {a.path.name}")

    def all_maps(self):
        return self.c_maps | self.s_maps | {self.mid}

    def check_map_ref(self, where, v, side_maps):
        for i in int_list(v):
            if i != 0 and i != self.mid and i not in side_maps:
                self.err(f"{where}: map id {i} does not exist")

    # -- client fieldData row
    def client_fielddata(self):
        ft = self.fielddata
        ms = ft.find_live(r'\t<fieldData id="0*%d">.*?</fieldData>[^\S\n]*\r?\n' % self.ref, re.S)
        if not ms:
            return None
        m = ms[0]
        block = m.group(0)
        refxb = re.search(r'<xblock name="([^"]*)"', block).group(1)
        block = re.sub(r'(<fieldData id=")[^"]*"', lambda q: q.group(1) + str(self.mid) + '"', block, count=1)
        block = re.sub(r'(<xblock name=")[^"]*"', lambda q: q.group(1) + self.xb.upper() + '"', block, count=1)
        for a in ("revivalreturnid", "enterreturnid"):
            if get_attr(block, a) == str(self.ref):
                block = re.sub(r'(\s%s=")%d"' % (a, self.ref), lambda q: q.group(1) + str(self.mid) + '"', block)
        uni = lambda t: attr_universe([ft.text], t)
        ov = self.side_overrides("client_map", uni, "client fielddata")
        block = apply_tag_overrides(self.drop_minimap_invisible(block, ov), ov, uni, "client fielddata")
        self.validate_env(block, "client fielddata", self.c_maps)
        ft.insert_after(m, block)
        self.emit("client-xml", "table/fielddata.xml", ft)
        return refxb.lower()

    # -- server map/<id>.xml
    def server_maptexts(self):
        if self.s_maptexts is None:
            self.s_maptexts = [XText(self.sx.file(n)).text for n in self.sx.under("map/")
                               if n.lower().endswith(".xml")]
        return self.s_maptexts

    def server_map(self):
        f = self.sx.file(f"map/{self.ref:08d}.xml")
        if f is None:
            return None
        xt = XText(f)
        refxb = re.search(r'<xblock name="([^"]*)"', xt.text).group(1)
        t = re.sub(r'(<xblock name=")[^"]*"', lambda q: q.group(1) + self.xb.upper() + '"', xt.text, count=1)
        for a in ("revivalreturnid", "enterreturnid"):
            t = re.sub(r'(\s%s=")0*%d"' % (a, self.ref), lambda q: q.group(1) + str(self.mid) + '"', t)
        uni = lambda tag: attr_universe(self.server_maptexts(), tag)
        ov = self.side_overrides("server_map", uni, "server map")
        t = apply_tag_overrides(self.drop_minimap_invisible(t, ov), ov, uni, "server map")
        self.validate_env(t, "server map", self.s_maps)
        xt.text = t
        self.emit("server-xml", f"map/{self.mid:08d}.xml", xt)
        return refxb.lower()

    def side_overrides(self, key, uni, where):
        """spec "map" (both sides) + spec <key> (this side only). A shared attr the side never uses is
        skipped with a note; it must be known on the other side (checked there / at the end)."""
        ov = {}
        for tag, attrs in self.spec.get("map", {}).items():
            for a, v in attrs.items():
                if a in uni(tag):
                    ov.setdefault(tag, {})[a] = v
                else:
                    self.notes.append(f"{where}: <{tag} {a}> not used on this side, skipped")
                    self.one_sided.setdefault((tag, a), []).append(where)
        for tag, attrs in self.spec.get(key, {}).items():
            ov.setdefault(tag, {}).update(attrs)
        return ov

    def validate_env(self, block, where, side_maps):
        for a in ("revivalreturnid", "enterreturnid"):
            v = get_attr(block, a)
            if v:
                self.check_map_ref(f"{where} {a}", v, side_maps | {self.mid})

    # -- strings
    def names(self, area, arch, langs_glob):
        names = self.spec.get("names", {})
        if not names:
            self.err("spec: names {lang: text} is required")
            return
        for n in arch.under("string/"):
            mm = re.fullmatch(r"string/([a-z]+)/mapname\.xml", n.lower())
            if not mm or (langs_glob and mm.group(1) not in langs_glob):
                continue
            lang = mm.group(1)
            name = names.get(lang) or names.get("en") or next(iter(names.values()))
            xt = XText(arch.file(n))
            ms = xt.find_live(r'[^\S\n]*<key id="0*%d"[^>]*/>[^\S\n]*\r?\n' % self.ref)
            if not ms:
                self.notes.append(f"{area} {n}: no row for {self.ref}; not written")
                continue
            row = ms[0].group(0)
            pad = re.search(r'<key id="(0*)\d+"', row).group(1)
            row = re.sub(r'(<key id=")\d+"', lambda q: q.group(1) + (f"{self.mid:08d}" if pad else str(self.mid)) + '"', row, count=1)
            row = set_attr(re.search(r"<key [^>]*/>", row).group(0), "name", name).join(
                re.split(r"<key [^>]*/>", row, maxsplit=1))
            xt.insert_after(ms[0], row)
            self.emit(area, n, xt)

    # -- mapxblock + triggers
    def mapxblock(self, area, arch, refxb):
        f = arch.file(f"mapxblock/{refxb}.xml")
        if f is None:
            self.notes.append(f"{area}: reference has no mapxblock/{refxb}.xml")
            return
        xt = XText(f)
        ov = self.spec.get("mapxblock", {})
        if ov:
            arch.fetch("mapxblock/")
            texts = [XText(arch.file(n)).text for n in arch.under("mapxblock/")]
            xt.text = apply_tag_overrides(xt.text, ov, lambda t: attr_universe(texts, t), f"{area} mapxblock")
        if self.minimap:
            block = self.minimap[1].replace("\r\n", "\n").replace("\n", xt.nl)
            t = re.sub(r"[^\S\n]*<minimap>.*?</minimap>[^\S\n]*\r?\n", "", xt.text, flags=re.S)
            m = re.search(r"<ms2>[^\S\n]*\r?\n", t)
            if m is None:
                self.err(f"{area} mapxblock/{refxb}.xml: no <ms2> root")
            else:
                xt.text = t[:m.end()] + block + t[m.end():]
        self.emit(area, f"mapxblock/{self.xb}.xml", xt)

    def triggers(self, area, arch, refxb):
        td = self.spec.get("trigger_dir")
        if td:
            for p in sorted(Path(td).rglob("*.xml")):
                self.emit(area, f"trigger/{self.xb}/{p.relative_to(td).as_posix()}", p)
            return
        if not self.spec.get("copy_triggers", True):
            return
        for n in arch.under(f"trigger/{refxb}/"):
            self.emit(area, f"trigger/{self.xb}/{n[len(f'trigger/{refxb}/'):]}", arch.file(n))

    # -- dungeon rooms
    def dungeon_room(self):
        dr = self.spec.get("dungeon_room")
        if not dr:
            return
        rid, rref = int(dr["id"]), int(dr["clone_from"])
        sides = (("client-xml", self.cx, "table/dungeonroom.xml", self.c_maps, dr.get("client_set", {}), False),
                 ("server-xml", self.sx, "table/na/dungeonroom.xml", self.s_maps, dr.get("server_set", {}), True))
        sv_drop = XText(self.sv.file("table/Server/individualItemDrop_Final.xml")).text
        sv_global = XText(self.sv.file("table/Server/globalDropItemBox_Final.xml")).text
        drop_ids = ids_of(sv_drop, "dropBox", "dropBoxID") | ids_of(sv_global, "dropBox", "dropBoxID") | {0}
        factor_ids = ids_of(XText(self.sv.file("table/Server/npcStatFactorByPlayerCount.xml")).text,
                            "PlayerCountFactor", "factorID")
        for area, arch, name, side_maps, extra, pad in sides:
            xt = XText(arch.file(name))
            rooms = ids_of(xt.text, "dungeonRoom", "dungeonRoomID")
            if rid in rooms:
                self.err(f"dungeon_room id {rid} already exists in {area} {name}")
            ms = xt.find_live(r'[^\S\n]*<dungeonRoom dungeonRoomID="%d"[^>]*/>[^\S\n]*\r?\n' % rref)
            if not ms:
                self.err(f"dungeon_room clone_from {rref}: no row in {area} {name}")
                continue
            row = ms[0].group(0)
            tag = re.search(r"<dungeonRoom [^>]*/>", row).group(0)
            uni = attr_universe([xt.text], "dungeonRoom")
            sets = dict(dr.get("set", {}), **extra)
            sets["dungeonRoomID"] = rid
            sets["fieldIDs"] = f"{self.mid:08d}" if pad else str(self.mid)
            for a, v in sets.items():
                if a not in uni:
                    if a in dr.get("set", {}) and a not in extra:
                        self.notes.append(f"{area} dungeonRoom: {a} not used on this side, skipped")
                        continue
                    raise SpecError(f"{area} dungeonRoom: attribute {a} is not used by any shipped row")
                tag = set_attr(tag, a, v)
            # validate referenced ids
            arch_txt = lambda n: XText(arch.file(n)).text if arch.has(n) else ""
            checks = {
                "lobbyFieldID": ("map", side_maps), "fieldIDs": ("map", side_maps),
                "unionRewardID": ("dungeonRoom", rooms),
                "seasonRankRewardID": ("DungeonRankReward", ids_of(arch_txt("table/dungeonrankreward.xml"),
                                                                   "DungeonRankReward", "rewardID")),
                "partyMissions": ("DungeonMission", ids_of(arch_txt("table/dungeonmission.xml"), "DungeonMission", "id")),
                "userMissions": ("DungeonMission", ids_of(arch_txt("table/dungeonmission.xml"), "DungeonMission", "id")),
                "roundID": ("DungeonRoundGroup", ids_of(arch_txt("table/dungeonrounddata.xml"), "DungeonRoundGroup", "id")),
                "playerCountFactorID": ("PlayerCountFactor", factor_ids),
                "rewardLimitedDropBoxIds": ("dropBox", drop_ids), "rewardLimitedDropBoxIds2": ("dropBox", drop_ids),
                "rewardUnlimitedDropBoxIds": ("dropBox", drop_ids), "findHelperRewardDropBoxIds": ("dropBox", drop_ids),
            }
            for a, (kind, known) in checks.items():
                v = get_attr(tag, a)
                if not v:
                    continue
                for i in int_list(v):
                    if kind == "map":
                        if i != self.mid and i not in side_maps:
                            self.err(f"{area} dungeonRoom {a}: map {i} does not exist")
                    elif i != 0 and i not in known:
                        self.err(f"{area} dungeonRoom {a}: {kind} {i} does not exist")
            row = row.replace(re.search(r"<dungeonRoom [^>]*/>", row).group(0), tag, 1)
            xt.insert_after(ms[0], row)
            self.emit(area, name, xt)

    # -- server InstanceField
    def instance_field(self):
        mode = self.spec.get("instance_field", "clone")
        if mode is False:
            return
        name = "table/Server/InstanceField.xml"
        xt = XText(self.sv.file(name))
        ms = [m for m in xt.find_live(r'[^\S\n]*<InstanceField [^>]*/>[^\S\n]*\r?\n')
              if self.ref in int_list(get_attr(m.group(0), "fieldIDs") or "")]
        if not ms:
            if isinstance(mode, dict):
                self.err(f"instance_field: reference {self.ref} has no InstanceField row to clone")
            else:
                self.notes.append(f"server: {self.ref} has no InstanceField row (not an instanced map); none written")
            return
        row = ms[0].group(0)
        tag = re.search(r"<InstanceField [^>]*/>", row).group(0)
        uni = attr_universe([xt.text], "InstanceField")
        used = ids_of(xt.text, "InstanceField", "instanceID")
        sets = dict(mode) if isinstance(mode, dict) else {}
        # next free id after the highest one of the same instanceType (ids are grouped by type)
        itype = get_attr(tag, "instanceType")
        same = [int(get_attr(m.group(0), "instanceID")) for m in xt.find_live(r'<InstanceField [^>]*/>')
                if get_attr(m.group(0), "instanceType") == itype]
        nxt = max(same) + 1
        while nxt in used:
            nxt += 1
        sets.setdefault("instanceID", nxt)
        if int(sets["instanceID"]) in used:
            self.err(f"instance_field instanceID {sets['instanceID']} already used")
        sets["fieldIDs"] = str(self.mid)
        for a, v in sets.items():
            if a not in uni:
                raise SpecError(f"InstanceField: attribute {a} is not used by any shipped row")
            tag = set_attr(tag, a, v)
        xt.insert_after(ms[0], row.replace(re.search(r"<InstanceField [^>]*/>", row).group(0), tag, 1))
        self.emit("server", name, xt)

    # -- resources
    def resources(self, refxb):
        sp = self.spec
        src = Path(sp["xblock_file"]) if sp.get("xblock_file") else self.ex.file(f"xblock/{refxb}.xblock")
        if src is None:
            self.err(f"Exported.m2d has no xblock/{refxb}.xblock")
        else:
            self.emit("exported", f"xblock/{self.xb}.xblock", src)
        src = Path(sp["tok_file"]) if sp.get("tok_file") else self.pt.file(f"{refxb}.tok")
        if src is None:
            self.notes.append(f"PrecomputedTerrain.m2d has no {refxb}.tok; none written")
        else:
            self.emit("terrain", f"{self.xb}.tok", src)
        mode = self.minimap_mode()
        if mode == "none":
            return
        if self.minimap:
            self.emit("image", f"map/minimap/{self.mid:08d}.dds", self.minimap[0])
            return
        src = Path(sp["minimap_file"]) if sp.get("minimap_file") else self.im.file(f"map/minimap/{self.ref:08d}.dds")
        if src is None:
            self.notes.append(f"Image.m2d has no map/minimap/{self.ref:08d}.dds (reference has no minimap)")
        else:
            self.emit("image", f"map/minimap/{self.mid:08d}.dds", src)

    # -- asset-web-metadata: the client resolves urn:emergent-world:<XBLOCK> through these triples
    def asset_web(self, refxb):
        """Add the new xblock's triples: every triple of the reference xblock's urn:uuid, with a new uuid and name."""
        rows = {}
        for n in self.aw.names:
            if n.lower().endswith(".nt"):
                rows[n] = self.aw.file(n).read_bytes()
        rel = rows.get("relpath.nt")
        if rel is None:
            self.err("asset-web-metadata.m2d has no relpath.nt")
            return
        find = lambda xb: re.search(rb'^<(urn:uuid:[^>]+)> <[^>]*/relpath> "/Exported/XBlock/(%s)\.xblock"\.$'
                                    % re.escape(xb.encode()), rel, re.M | re.I)
        if find(self.xb):
            self.err(f"xblock name {self.xb}: asset-web-metadata.m2d already has an entry")
        m = find(refxb)
        if not m:
            self.err(f"asset-web-metadata.m2d has no relpath row for {refxb}")
            return
        ref_urn, ref_name = m.group(1), m.group(2)
        new_name = (self.xb.upper() if ref_name.isupper() else self.xb).encode()
        new_urn = f"urn:uuid:{uuid.uuid5(uuid.NAMESPACE_URL, 'ms2-custom-xblock:' + self.xb)}".encode()
        triples = []
        for n, data in rows.items():
            lines = [l for l in data.split(b"\n") if l.startswith(b"<" + ref_urn + b">")]
            if not lines:
                continue
            new = [l.replace(ref_urn, new_urn, 1).replace(ref_name, new_name) for l in lines]
            sep = b"" if data.endswith(b"\n") else b"\n"
            dst = self.out / "awm" / n
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_bytes(data + sep + b"\n".join(new) + b"\n")
            self.written.setdefault("awm", []).append(n)
            triples += [{"file": n, "triple": l.decode()} for l in new]
        self.asset_web_info = {"urn": new_urn.decode(), "reference_urn": ref_urn.decode(), "triples": triples}

    # -- minimap
    def minimap_mode(self):
        sp = self.spec
        m = sp.get("minimap", "generate" if not sp.get("minimap_file") else "file")
        if sp.get("minimap_file"):
            return "file"
        if m in (False, None, "none", "false"):
            return "none"
        if m not in ("generate", "reference"):
            raise SpecError(f'spec minimap: "generate", "reference" or false, not {m!r}')
        return m

    def generate_minimap(self):
        """Run minimap.py on the new map's xblock; sets self.minimap = (dds path, <minimap> block) or None."""
        self.minimap = None
        if self.minimap_mode() != "generate":
            return
        ms = re.search(r'<fieldData id="0*%d">.*?<xblock name="([^"]*)"' % self.ref, self.fielddata.text, re.S)
        refxb = ms.group(1).lower() if ms else None
        sp = self.spec
        xbf = Path(sp["xblock_file"]) if sp.get("xblock_file") else (self.ex.file(f"xblock/{refxb}.xblock") if refxb else None)
        if xbf is None:
            self.notes.append("minimap: no xblock to render; using the reference's DDS")
            return
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        try:
            import minimap
            work = self.out / "minimap-work"
            work.mkdir(parents=True, exist_ok=True)
            res = self.sources["exported"].parent
            geom, solids = minimap.run_tokgeom(res, xbf, work / self.xb, minimap.default_cache(),
                                               sp.get("minimap_project"))
            dds = work / f"{self.mid:08d}.dds"
            block = minimap.make(geom, solids, self.mid, dds, png=work / f"{self.mid:08d}.png")
        except (Exception, SystemExit) as e:
            self.notes.append(f"minimap: generation failed ({str(e).strip()[:300]}); using the reference's DDS")
            return
        self.minimap = (dds, block)
        self.notes.append(f"minimap: generated from {xbf.name} (preview {work.name}/{self.mid:08d}.png)")

    def drop_minimap_invisible(self, text, overrides):
        if self.minimap and "minimapInvisible" not in overrides.get("property", {}):
            text = re.sub(r'\s+minimapInvisible="[^"]*"', "", text)
        return text

    def run(self):
        self.notes = []
        self.one_sided = {}
        self.load()
        if self.errors:
            return False
        self.generate_minimap()
        crefxb = self.client_fielddata()
        srefxb = self.server_map()
        if crefxb and srefxb and crefxb != srefxb:
            self.notes.append(f"client xblock {crefxb} != server xblock {srefxb}; using the client one for resources")
        refxb = self.refxb = crefxb or srefxb
        for (tag, a), wh in self.one_sided.items():
            if len(wh) > 1:
                raise SpecError(f"map: <{tag} {a}> is not used by any shipped client or server row")
        self.names("client-xml", self.cx, None)
        self.names("server-xml", self.sx, {"en"})
        for area, arch in (("client-xml", self.cx), ("server-xml", self.sx)):
            self.mapxblock(area, arch, refxb)
            self.triggers(area, arch, refxb)
        self.dungeon_room()
        self.instance_field()
        self.resources(refxb)
        self.asset_web_info = None
        self.asset_web(refxb)
        manifest = {"map_id": self.mid, "xblock": self.xb, "clone_from": self.ref, "reference_xblock": refxb,
                    "archives": {"client-xml": str(self.sources["client_xml"]),
                                 "server-xml": str(self.sources["server_xml"]),
                                 "server": str(self.sources["server_m2d"]),
                                 "exported": str(self.sources["exported"]),
                                 "terrain": str(self.sources["terrain"]),
                                 "image": str(self.sources["image"]),
                                 "awm": str(self.sources["awm"])},
                    "asset_web": self.asset_web_info,
                    "written": self.written, "notes": self.notes}
        (self.out / "manifest.json").write_text(json.dumps(manifest, indent=1, ensure_ascii=False))
        return not self.errors


SPEC_PATH_KEYS = ("trigger_dir", "xblock_file", "tok_file", "minimap_file", "minimap_project")


def load_spec(path):
    p = Path(path)
    if p.suffix == ".toml":
        import tomllib
        spec = tomllib.loads(p.read_text())
    else:
        spec = json.loads(p.read_text())
    for k in SPEC_PATH_KEYS:
        v = spec.get(k)
        if not v or os.path.isabs(v):
            continue
        for base in (p.resolve().parent, Path.cwd(), REPO):
            if (base / v).exists():
                spec[k] = str(base / v)
                break
        else:
            raise SpecError(f"spec {k}: {v} not found next to the spec, in the current directory or in the repo")
    return spec


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("spec")
    ap.add_argument("-o", "--out", required=True)
    ap.add_argument("--refresh", action="store_true", help="re-list/re-extract the reference archives")
    a = ap.parse_args()
    out = Path(a.out)
    for area in ("client-xml", "server-xml", "server", "exported", "terrain", "image", "awm"):
        shutil.rmtree(out / area, ignore_errors=True)
    try:
        g = Gen(load_spec(a.spec), out, a.refresh)
        ok = g.run()
    except SpecError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    for n in g.notes:
        print(f"note: {n}")
    for e in g.errors:
        print(f"error: {e}", file=sys.stderr)
    if not ok:
        return 1
    for area, names in g.written.items():
        print(f"{area}: {len(names)} files")
    print(f"wrote {out}/manifest.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
